export type Case = {
  id: string;
  title: string;
  owner: string;
  description: string;
  scope: string;
  status: string;
  synthetic: boolean;
  created_at: string;
};
export type Evidence = {
  id: string;
  case_id: string;
  filename: string;
  source_type: string;
  size: number;
  sha256: string;
  observed_sha256: string | null;
  verification_status: string;
  verified_at: string;
  received_at: string;
  received_by: string;
  collected_by: string;
  acquired_at: string;
  source_description: string;
  notes: string;
  custodian: string;
  parser_status: string;
  metadata: Record<string, unknown>;
  warnings: string[];
  event_count: number;
};
